const TILE_CHARS = '#XB?M=^L<>12!U';
function buildLevel(def) {
  const H = def.h, rows = Array.from({ length: H }, () => '');
  def.chunks.forEach((ch, ci) => {
    const cr = ch.map(r => r.replace(/ /g, '')); const w = Math.max(...cr.map(r => r.length));
    if (cr.some(r => r.length !== w) || cr.length > H) console.warn('チャンクの行幅が不一致', def.name, ci, cr.map(r => r.length));
    for (let y = 0; y < H; y++) { const i = y - (H - cr.length); rows[y] += (i >= 0 ? cr[i] : '').padEnd(w, '.'); }
  });
  const W = rows[0].length;
  for (let y = 0; y < (def.ceil || 0); y++) rows[y] = '#'.repeat(W);
  const tiles = new Array(W * H), spawns = [];
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const c = rows[y][x];
    if (TILE_CHARS.includes(c)) tiles[y * W + x] = c;
    else if (c === '.') tiles[y * W + x] = '.';
    else { spawns.push({ c, x, y }); tiles[y * W + x] = c === 'o' ? 'L' : (c === 'T' ? 'T' : (c === 'R' ? 'R' : '.')); }
  }
  return { w: W, h: H, tiles, spawns };
}
